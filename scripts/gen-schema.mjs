#!/usr/bin/env node
/**
 * Generates src/backend/schema.generated.ts from the original SQL table definitions
 * (legacy-supabase/migrations/*.sql). It captures, per table: columns, defaults, NOT NULL,
 * primary key, unique constraints, foreign keys and generated-column expressions.
 * The Firestore backend uses it for defaults, embeds (joins) and composite keys.
 *
 *   node scripts/gen-schema.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migDir = join(root, 'legacy-supabase', 'migrations')
const sql = readdirSync(migDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => readFileSync(join(migDir, f), 'utf8'))
  .join('\n')
  .replace(/--[^\n]*/g, '')

/** split on commas at paren depth 0 */
function splitTop(s) {
  const out = []
  let depth = 0
  let quote = false
  let cur = ''
  for (const ch of s) {
    if (ch === "'") quote = !quote
    if (!quote) {
      if (ch === '(' || ch === '[') depth++
      if (ch === ')' || ch === ']') depth--
      if (ch === ',' && depth === 0) {
        out.push(cur.trim())
        cur = ''
        continue
      }
    }
    cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

/** extract balanced (...) starting at index of '(' */
function balanced(s, start) {
  let depth = 0
  let quote = false
  for (let i = start; i < s.length; i++) {
    const ch = s[i]
    if (ch === "'") quote = !quote
    if (quote) continue
    if (ch === '(') depth++
    if (ch === ')') {
      depth--
      if (depth === 0) return s.slice(start + 1, i)
    }
  }
  throw new Error('unbalanced')
}

function parseDefault(expr) {
  const e = expr.trim()
  if (/^gen_random_uuid\(\)$/i.test(e)) return { kind: 'uuid' }
  if (/^auth\.uid\(\)$/i.test(e)) return { kind: 'uid' }
  if (/^now\(\)$/i.test(e)) return { kind: 'now' }
  if (/^current_date$/i.test(e)) return { kind: 'today' }
  if (/^(true|false)$/i.test(e)) return { kind: 'value', value: e.toLowerCase() === 'true' }
  if (/^-?\d+(\.\d+)?$/.test(e)) return { kind: 'value', value: Number(e) }
  let m = e.match(/^'((?:[^']|'')*)'::jsonb$/is)
  if (m) return { kind: 'value', value: JSON.parse(m[1].replace(/''/g, "'")) }
  m = e.match(/^'((?:[^']|'')*)'(::[a-z_.]+)?$/is)
  if (m) return { kind: 'value', value: m[1].replace(/''/g, "'") }
  m = e.match(/^array\[(.*)\]$/is)
  if (m) return { kind: 'value', value: splitTop(m[1]).map((x) => x.trim().replace(/^'|'$/g, '')) }
  return { kind: 'unknown', expr: e }
}

const tables = {}
const re = /create table public\.([a-z_]+)\s*\(/gi
let m
while ((m = re.exec(sql))) {
  const name = m[1]
  const body = balanced(sql, m.index + m[0].length - 1)
  const t = { columns: {}, pk: [], fks: {}, uniques: [] }
  for (const part of splitTop(body)) {
    const p = part.replace(/\s+/g, ' ').trim()
    let mm
    if ((mm = p.match(/^primary key \(([^)]+)\)/i))) {
      t.pk = mm[1].split(',').map((x) => x.trim())
      continue
    }
    if ((mm = p.match(/^unique \(([^)]+)\)/i))) {
      t.uniques.push(mm[1].split(',').map((x) => x.trim()))
      continue
    }
    if (/^constraint /i.test(p)) continue
    const col = p.match(/^([a-z_][a-z0-9_]*) ([a-z_.]+(?:\(\d+(?:,\d+)?\))?(?:\[\])?)(.*)$/i)
    if (!col) continue
    const [, cname, ctype, rest] = col
    const c = { type: ctype.toLowerCase() }
    if (/not null/i.test(rest) || /primary key/i.test(rest)) c.notNull = true
    if (/primary key/i.test(rest)) t.pk = [cname]
    if (/\bunique\b/i.test(rest)) t.uniques.push([cname])
    const ref = rest.match(/references public\.([a-z_]+)\(([a-z_]+)\)(?: on delete (cascade|set null|restrict))?/i)
    if (ref) t.fks[cname] = { table: ref[1], column: ref[2], onDelete: (ref[3] ?? 'restrict').toLowerCase() }
    const gen = rest.match(/generated always as \((.*)\) stored/i)
    if (gen) c.generated = gen[1].trim()
    if (/generated always as identity/i.test(rest)) c.identity = true
    // default: up to the next keyword
    const def = rest.match(/ default (.+?)(?= not null| check| references| unique| primary key| generated|$)/i)
    if (def) c.default = parseDefault(def[1])
    // Postgres array literal '{}' / '{a,b}' for array columns -> JS array
    if (c.default?.kind === 'value' && c.type.endsWith('[]') && typeof c.default.value === 'string' && /^\{.*\}$/.test(c.default.value))
      c.default.value = c.default.value.slice(1, -1).split(',').map((x) => x.trim()).filter(Boolean)
    if (/^text$|^jsonb$|^boolean$|^int$|^bigint$|^uuid$|^date$|^timestamptz$|^numeric/.test(c.type) === false && /project_status/.test(c.type)) c.type = 'text'
    t.columns[cname] = c
  }
  if (!t.pk.length && t.columns.id) t.pk = ['id']
  tables[name] = t
}

const banner = `/* AUTO-GENERATED by scripts/gen-schema.mjs from legacy-supabase/migrations — do not edit by hand. */\n`
const out =
  banner +
  `import type { TableSchema } from './types'\n\nexport const TABLES: Record<string, TableSchema> = ${JSON.stringify(tables, null, 2)}\n`
writeFileSync(join(root, 'src', 'backend', 'schema.generated.ts'), out)
console.log(`schema: ${Object.keys(tables).length} tables`)
for (const [n, t] of Object.entries(tables)) {
  for (const [c, d] of Object.entries(t.columns)) if (d.default?.kind === 'unknown') console.log(`  unknown default ${n}.${c}: ${d.default.expr}`)
}

// ----------------------------------------------------------------------------- seed (roles, permissions, matrix, numbering)
/** top-level (...) groups of a VALUES list, respecting quotes */
function tuples(block) {
  const out = []
  let depth = 0
  let quote = false
  let start = -1
  for (let i = 0; i < block.length; i++) {
    const ch = block[i]
    if (ch === "'") quote = !quote
    if (quote) continue
    if (ch === '(' && depth++ === 0) start = i + 1
    if (ch === ')' && --depth === 0) out.push(block.slice(start, i))
  }
  return out.map((t) => splitTop(t).map((v) => v.trim().replace(/^'|'$/g, '').replace(/''/g, "'")))
}
const rolesBlock = sql.match(/insert into public\.roles \(key, name, description, is_system\) values([\s\S]*?);/i)[1]
const permsBlock = sql.match(/insert into public\.permissions \(key, module, description\) values([\s\S]*?);/i)[1]
const matrixBlock = sql.match(/with matrix\(role_key, perm_key\) as \(values([\s\S]*?)\n\)/i)[1]
const numBlock = sql.match(/insert into public\.numbering_sequences \(key, label, prefix\) values([\s\S]*?);/i)[1]
const catBlock = sql.match(/insert into public\.material_categories\(name\) values([\s\S]*?);/i)[1]
const seed = {
  roles: tuples(rolesBlock).map(([key, name, description, isSystem]) => ({ key, name, description, is_system: isSystem === 'true' })),
  permissions: tuples(permsBlock).map(([key, module, description]) => ({ key, module, description })),
  matrix: tuples(matrixBlock).map(([role, perm]) => [role, perm]),
  numbering: tuples(numBlock).map(([key, label, prefix]) => ({ key, label, prefix })),
  materialCategories: tuples(catBlock).map(([name]) => name),
}
writeFileSync(
  join(root, 'src', 'backend', 'seed.generated.ts'),
  banner + `export const SEED = ${JSON.stringify(seed, null, 2)} as const\n`,
)
console.log(`seed: ${seed.materialCategories.length} material categories, ${seed.roles.length} roles, ${seed.permissions.length} permissions, ${seed.matrix.length} grants, ${seed.numbering.length} sequences`)
